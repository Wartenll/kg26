# Проверим все x от 0 до 24 и найдем наибольшее подходящее
max_x = -1
result = 0

for x in range(25):
    # 1-е число: 11353x_25
    n1 = 1 * 25 ** 5 + 1 * 25 ** 4 + 3 * 25 ** 3 + 5 * 25 ** 2 + 3 * 25 + x

    # 2-е число: 135x21_25
    n2 = 1 * 25 ** 5 + 3 * 25 ** 4 + 5 * 25 ** 3 + x * 25 ** 2 + 2 * 25 + 1

    S = n1 + n2

    if S % 24 == 0:
        max_x = x
        result = S // 24

# Выводим результат для наибольшего найденного x
print(result)